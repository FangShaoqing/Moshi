def can_domain_happen(domain: str, age: int) -> bool:
    """人生阶段闸门：这个领域在"这个年龄"是否允许发生。"""
    start = DOMAIN_AGE_START.get(domain, 99)
    return age >= start


def render_event(domain: str, age: int, favorable: bool,
                 rng: Any | None = None, used: set[str] | None = None,
                 family_class: str | None = None) -> str:
    """按 领域 × 年龄段 × 顺/逆风 渲染出"一件具体的事"。

    - 用 rng（若给）从候选里随机选一条，避免永远取第一条。
    - used（若给）是"这条人生已用过的叙事"，用来去重：尽量选没用过的，
      全部用过后才允许重复 → 同一格多条候选才有意义。
    """
    import random as _random

    stage = _stage_of(age)
    # V5 同源：小康/富足且该领域有阶层变体 → 用变体；否则原叙事
    if family_class in ("小康", "富足"):
        var_choices = (CLASS_NARRATIVES.get(domain, {})
                       .get(stage, {})
                       .get("favorable" if favorable else "adverse"))
        if var_choices:
            choices = var_choices
        else:
            choices = (EVENT_NARRATIVES.get(domain, {})
                       .get(stage, {})
                       .get("favorable" if favorable else "adverse"))
    else:
        choices = (EVENT_NARRATIVES.get(domain, {})
                   .get(stage, {})
                   .get("favorable" if favorable else "adverse"))
    if not choices:
        # 退化：用"领域+方向+年龄"的朴素具体表述
        direction = "顺" if favorable else "逆"
        return f"{age}岁，在「{domain}」上经历了一次{direction}风"
    # 去重：优先选"这条人生还没用过的"叙事
    if used is not None:
        fresh = [c for c in choices if c not in used]
        if fresh:
            choices = fresh
    pick = rng.choice(choices) if rng is not None else choices[0]
    if used is not None:
        used.add(pick)
    return f"{age}岁，{pick}"


@dataclass
class WorldState:
    """世界状态：每个情境的"响应基线" r ∈ [-1,1]。

    r > 0：世界这个领域正顺风（投入容易得到回报 / 世界友好）
    r < 0：世界这个领域正逆风（投入容易受挫 / 世界冷酷）
    r 自己演化：随机游走 + 向 0（或时代基线）回归 —— 世界的运势会漂移、有起有伏。
    """
    responses: dict[str, float]

    def step(self, rng: Any, drift: float = 0.06, regress: float = 0.06,
             big_event_p: float = 0.03) -> None:
        """世界响应基线演化一步：r' = (1-regress)*r + regress*middle + 随机漂移 + 世界大事件跳变。

        - 普通漂移（drift=0.06）：世界运势温和起伏（大部分"日常"）。
        - 世界大事件（big_event_p=0.03，降低）：**稀有而重大**——约 1/33 的概率出现显著跳变，
          这才是"改变人生的事"。大幅事件用 0.6~1.1 的跳变（更重）。
        - 效果：事件冲击呈极端重尾——绝大多数温和小事（日常，被消化）+ 极少数重大事件
          （真正塑造人格）→ 对应"成熟：被少数大事塑造 + 日常被磨平"（设计 17）。
        """
        for d in DOMAINS:
            r = self.responses[d]
            # 普通漂移（温和起伏 = 大部分小事）
            r = (1 - regress) * r + regress * 0.0 + rng.uniform(-drift, drift)
            # 世界大事件（小概率重尾跳变 = 改变人生的事；稀有而重大）
            if rng.random() < big_event_p:
                jump = rng.uniform(0.6, 1.1)
                r += jump if rng.random() < 0.5 else -jump
            self.responses[d] = max(-1.0, min(1.0, r))


# ── 情境系数：某情境的"顺风/逆风"会推状态的哪些维度（方向 + 强度）──
# 统一约定：系数为正的维度，顺风(+)时上升、逆风(-)时下降；负系数则反之。
DOMAIN_COEFF: dict[str, tuple[float, ...]] = {
    "信任":       (0.06, 0.02, 0.03, 0.10, 0.30, 0.16),   # 主要推 Trust/Belonging
    "亲密关系":   (0.12, 0.10, -0.02, 0.10, 0.22, 0.16),
    "工作与生计": (0.06, 0.16, 0.24, 0.26, 0.04, 0.02),
    "金钱":       (0.04, 0.06, 0.18, 0.14, 0.02, 0.02),
    "自我价值":   (0.12, 0.06, 0.10, 0.30, 0.08, 0.05),
    "归属":       (0.12, 0.04, 0.02, 0.10, 0.16, 0.32),
    "未来":       (0.08, 0.16, 0.20, 0.16, 0.02, 0.04),
    "表达自我":   (0.10, 0.20, 0.10, 0.18, 0.02, 0.02),
}


def effective_investment(state: StateVector, domain: str) -> float:
    """行为函数 h(S)：从状态读出"她此刻在该情境上的投入度" ∈ [0,1]。

    V2 用固定线性读出；V3 用"各维度贡献 + 轻微非线性（饱和）"，让行为体现状态的复合影响。
    """
    v = state.as_list()
    # 各情境的"投入权重"（哪些状态维度支撑"愿意投精力在这里"）
    weights: dict[str, tuple[float, ...]] = {
        "信任":       (0.0, 0.0, 0.1, 0.2, 0.6, 0.1),
        "亲密关系":   (0.3, 0.1, 0.0, 0.2, 0.3, 0.1),
        "工作与生计": (0.1, 0.3, 0.3, 0.3, 0.0, 0.0),
        "金钱":       (0.0, 0.3, 0.4, 0.2, 0.1, 0.0),
        "自我价值":   (0.2, 0.0, 0.2, 0.5, 0.1, 0.0),
        "归属":       (0.2, 0.0, 0.0, 0.2, 0.3, 0.3),
        "未来":       (0.1, 0.2, 0.3, 0.2, 0.1, 0.1),
        "表达自我":   (0.2, 0.2, 0.1, 0.2, 0.1, 0.2),
    }
    w = weights.get(domain, (0.2,) * 6)
    raw = sum(a * b for a, b in zip(v, w))
    # 轻微非线性饱和：投入度不过分极端
    return max(0.0, min(1.0, raw))


def event_delta(state: StateVector, world: WorldState, domain: str) -> tuple[float, ...]:
    """事件强度：世界响应 × 行为投入 × 情境系数（向量，作用于 6 维状态）。

    这是"世界反馈"的核心 —— 世界顺风(+r) 且她投入高 → 正向推动；
    世界逆风(-r) 且她投入高 → 负向打击；投入低则影响弱（没怎么参与，不受深伤或深益）。
    """
    invested = effective_investment(state, domain)
    r = world.responses.get(domain, 0.0)
    coeff = DOMAIN_COEFF.get(domain, (0.0,) * 6)
    return tuple(invested * r * c for c in coeff)
